// es/fr henüz çevrilmedi → şimdilik TR'ye düşer (çeviriler sonra eklenecek, kullanıcı isteği).
const DICT: Record<Locale, Dict> = { tr: TR, en: EN, de: DE, es: TR, fr: TR };

/** Çeviri. Anahtar yoksa TR'ye, o da yoksa anahtarın kendisine düşer. {n} gibi yer tutucular doldurulur. */
export function t(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  let s = DICT[locale]?.[key] ?? DICT.tr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
